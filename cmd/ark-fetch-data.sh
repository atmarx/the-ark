#!/usr/bin/env bash
# ark-fetch-data.sh — mirror the Data Liberation Project dataset bucket
#
# Syncs https://dlp-cdn.muckrock.com/ to <staging>/data/dlp/
# Crawls the CDN's static HTML index pages to discover files, then
# downloads each one with curl.
#
# Skips:
#   - shortened_paths/   (duplicate data with shortened key names)
#   - index.html files   (generated indexes, not dataset content)
#   - already-downloaded files (unless --force)

ARK_DLP_BUCKET_URL="${ARK_DLP_BUCKET_URL:-https://dlp-cdn.muckrock.com}"

ark_fetch_data() {
    ark_load_config

    local dry_run=false
    local force=false

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --dry-run)  dry_run=true ;;
            --force)    force=true ;;
            *)          ark_die "Unknown flag: $1. Usage: ark fetch-data [--dry-run] [--force]" ;;
        esac
        shift
    done

    local data_dir
    data_dir="$(ark_data_dir)/dlp"

    ark_bold "Data Liberation Project — dataset sync"
    ark_info "  Source:      $ARK_DLP_BUCKET_URL"
    ark_info "  Destination: $data_dir"
    $dry_run && ark_warn "  (dry run — no files will be written)"
    echo

    $dry_run || mkdir -p "$data_dir"

    # ── Crawl HTML index pages to discover files ──────────────────────────────
    # The CDN serves static HTML indexes (generated by s3_generate_index.py),
    # not the S3 ListObjectsV2 API.  Folders link to subdir/index.html,
    # files link directly to the object.  We BFS through all index pages.
    ark_info "Crawling index pages..."

    local -a all_keys=()
    local -a queue=("")  # path prefixes to visit (root = empty string)
    local pages_crawled=0

    while [[ ${#queue[@]} -gt 0 ]]; do
        local prefix="${queue[0]}"
        queue=("${queue[@]:1}")

        # Build URL — root serves index at /, subfolders at prefix/index.html
        local fetch_url
        if [[ -z "$prefix" ]]; then
            fetch_url="$ARK_DLP_BUCKET_URL/"
        else
            local encoded_prefix
            encoded_prefix="$(printf '%s' "$prefix" \
                | sed 's|/$||' \
                | jq -Rr '[split("/") | .[] | select(. != "") | @uri] | join("/")')"
            fetch_url="$ARK_DLP_BUCKET_URL/${encoded_prefix}/index.html"
        fi

        local page_html
        if ! page_html="$(curl -sf --max-time 30 "$fetch_url" 2>/dev/null)"; then
            ark_warn "  Failed to fetch: $fetch_url"
            continue
        fi

        pages_crawled=$(( pages_crawled + 1 ))
        ark_dim "  [$pages_crawled] ${prefix:-(root)}"

        # Extract hrefs and classify as folders or files
        while IFS= read -r href; do
            [[ -z "$href" ]] && continue
            # Skip parent directory links
            [[ "$href" == "../index.html" ]] && continue

            if [[ "$href" == */index.html ]]; then
                # Folder link — queue for crawling
                local folder_name="${href%/index.html}"
                [[ "$folder_name" == "shortened_paths" ]] && continue
                queue+=("${prefix}${folder_name}/")
            else
                # File link — skip stray index.html refs
                [[ "$href" == "index.html" ]] && continue
                all_keys+=("${prefix}${href}")
            fi
        done < <(printf '%s' "$page_html" | grep -oP 'href="\K[^"]+(?=")')
    done

    local total="${#all_keys[@]}"

    if [[ $total -eq 0 ]]; then
        ark_warn "No files found while crawling."
        ark_dim  "  The CDN may have changed its index format."
        ark_dim  "  Try: curl -s '$ARK_DLP_BUCKET_URL/' | head -60"
        return 1
    fi

    ark_ok "Crawled $pages_crawled indexes, found $total files"
    echo

    # ── Download each file ────────────────────────────────────────────────────
    local downloaded=0
    local skipped=0
    local failed=0

    for i in "${!all_keys[@]}"; do
        local key="${all_keys[$i]}"
        local n=$(( i + 1 ))
        local dest="$data_dir/$key"
        local dest_dir
        dest_dir="$(dirname "$dest")"

        # Skip if already downloaded (unless --force)
        if [[ -f "$dest" ]] && ! $force; then
            skipped=$(( skipped + 1 ))
            ark_dim "  [$n/$total] skip  $key"
            continue
        fi

        # URL-encode each path segment (jq @uri), preserve slashes
        local encoded_key
        encoded_key="$(printf '%s' "$key" \
            | jq -Rr '[split("/") | .[] | @uri] | join("/")')"
        local url="$ARK_DLP_BUCKET_URL/$encoded_key"

        if $dry_run; then
            ark_info "  [$n/$total] would get  $key"
            downloaded=$(( downloaded + 1 ))
            continue
        fi

        ark_info "  [$n/$total] $key"
        mkdir -p "$dest_dir"

        if curl -sf -L \
                --max-time 600 \
                --retry 3 \
                --retry-delay 10 \
                --retry-connrefused \
                -o "$dest" \
                "$url" 2>/dev/null; then
            downloaded=$(( downloaded + 1 ))
        else
            ark_warn "  Failed: $key"
            rm -f "$dest"
            failed=$(( failed + 1 ))
        fi
    done

    echo
    if $dry_run; then
        ark_ok "Dry run complete: $downloaded files would be fetched, $skipped already present"
    else
        ark_ok "Done: $downloaded downloaded, $skipped already present, $failed failed"
        if [[ $failed -gt 0 ]]; then
            ark_warn "  $failed files failed — re-run to retry"
        fi
    fi
}
